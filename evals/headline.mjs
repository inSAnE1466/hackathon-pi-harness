// The headline: the one set of numbers every document and the video quote. It is built here from run files of the
// complete system (the pre-mask, BRANE with policy claims-v6.1, the second classifier, the agent with all tools) and
// stored as `headline` in evals/climb-summary.json by evals/slopes.mjs. Each value names its run file, its run time
// and the system that produced it. `renderHeadline` is the table the documents carry between the headline markers;
// scripts/numbers-check.mjs fails when a document's table, or a number in its prose, differs from this.
import { existsSync, readFileSync } from "node:fs";

const read = (file) => (existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : undefined);
export const COMPLETE_SYSTEM =
  "pre-mask, BRANE claims-v6.1, second classifier (classifier-v2), stricter route wins";
export const HEADLINE_DOCS = [
  "README.md",
  "submission/README.md",
  "docs/evals.md",
  "docs/track.md",
];
export const HEADLINE_BEGIN =
  "<!-- headline:begin (generated by node evals/slopes.mjs --docs from evals/climb-summary.json) -->";
export const HEADLINE_END = "<!-- headline:end -->";

/** Central European Time, which is UTC+1 in November. */
export const cet = (iso) => {
  if (!iso) return "not run";
  const d = new Date(new Date(iso).getTime() + 3_600_000);
  const two = (n) => String(n).padStart(2, "0");
  return `${d.getUTCDate()} Nov ${two(d.getUTCHours())}:${two(d.getUTCMinutes())} CET`;
};

export function buildHeadline(history) {
  const values = {};
  const put = (key, entry) => {
    if (entry.value !== undefined && entry.value !== null) values[key] = entry;
  };

  // Routing on omar-val: the complete-system row, whatever the keep rule said about it, beside the baseline.
  const row = (name) => history.rows.find((r) => r.track === "routing" && r.run === name);
  const full = row("s07-full-stack");
  const open = row("s00-open");
  const FULL_RUN = "evals/runs/s07-full-stack.json";
  const fullRun = read(FULL_RUN);
  if (full && fullRun) {
    const common = {
      split: `omar-val, a fixed sample of ${fullRun.bySet["omar-val"].n} rows (50 per route), one run`,
      system: COMPLETE_SYSTEM,
      run: FULL_RUN,
      at: fullRun.at,
    };
    const routing = [
      [
        "leak_rate",
        "Leak rate (should stay local or be refused, reached the cloud)",
        "leak_rate",
        "%",
      ],
      ["route_f1", "Route macro F1", "macro_f1", "0-1"],
      ["over_block", "Over-block rate (harmless rows kept local or refused)", "over_block", "%"],
      ["names_as_typed", "Names left as typed on the cloud", "name_leak_rate", "%"],
      [
        "span_leaks",
        "Labelled must-not-leave values found in a cloud payload",
        "span_leaks",
        "count",
      ],
    ];
    for (const [key, label, from, unit] of routing)
      put(key, {
        label,
        value: full.scores[from],
        unit,
        start: open?.scores[from] ?? null,
        ...common,
        ...(key === "span_leaks"
          ? { split: "39 health claims (228 labelled values) and 30 claims of our own, one run" }
          : {}),
      });
    // The other sets the same run scored, each whole except the adversarial variants (a fixed sample).
    const set = (name) => fullRun.bySet[name];
    const passed = (name) => fullRun.cases.filter((c) => c.set === name && c.pass).length;
    put("context_over_block", {
      label: "Lookup passages kept off the cloud (a cost: they hold no personal data)",
      value: full.scores.context_over_block,
      unit: "%",
      start: open?.scores.context_over_block ?? null,
      ...common,
      split: `${set("passages").n} corpus passages as the lookup tool returns them, one run`,
    });
    put("health_claims", {
      label: "Varied health claims kept local with no value leaked",
      value: passed("health"),
      of: set("health").n,
      unit: "of",
      ...common,
      split: "evals/golden/health.jsonl, one run",
    });
    put("adversarial_variants", {
      label: "Adversarial rewrites of our claims passed",
      value: passed("mutated"),
      of: set("mutated").n,
      unit: "of",
      ...common,
      split: `evals/golden/mutated.jsonl, a fixed sample of ${set("mutated").n} of 150, one run`,
    });
    put("omar_gate_tests", {
      label: "Omar Shalaby's gate tests passed",
      value: passed("omar-gate"),
      of: set("omar-gate").n,
      unit: "of",
      ...common,
      split: "evals/golden/omar-gate.jsonl, one run",
    });
    put("own_claims", {
      label: "Our own 30 claims routed correctly",
      value: passed("claims"),
      of: set("claims").n,
      unit: "of",
      ...common,
      split: "evals/golden/claims.jsonl, one run",
    });
    put("routing_kept", {
      label: "Keep rule on the complete-system routing row",
      value: full.kept ? "kept" : "reverted",
      unit: "text",
      reason: full.reason,
      ...common,
    });
  }

  // The locked split: one run of the complete system, never used to choose.
  const locked = history.locked;
  if (locked?.scores && locked.config === "s07-full-stack") {
    const common = {
      split: `omar-test, ${locked.rows} rows, locked, one run, never used to choose`,
      system: COMPLETE_SYSTEM,
      run: locked.run,
      at: locked.at,
    };
    put("locked_leak_rate", {
      label: "Leak rate, locked test",
      value: locked.scores.leak_rate,
      unit: "%",
      ...common,
    });
    put("locked_route_f1", {
      label: "Route macro F1, locked test",
      value: locked.scores.macro_f1,
      unit: "0-1",
      ...common,
    });
    put("locked_over_block", {
      label: "Over-block rate, locked test",
      value: locked.scores.over_block,
      unit: "%",
      ...common,
    });
    put("locked_names_as_typed", {
      label: "Names left as typed, locked test",
      value: locked.scores.name_leak_rate,
      unit: "%",
      ...common,
    });
  }

  // The mandatory tests and edge cases: the security CSV, worst of 5, in sequence.
  const CASES_RUN = "evals/runs/security-cases-full-stack.json";
  const cases = read(CASES_RUN);
  if (cases) {
    const common = {
      split: `submission/test_evidence_run.csv, each case ${cases.runs} times in sequence, worst of ${cases.runs}`,
      system: cases.system,
      run: CASES_RUN,
      at: cases.at,
    };
    put("mandatory_tests", {
      label: "Mandatory tests passed (T1 to T5)",
      value: cases.mandatory.passed,
      of: cases.mandatory.total,
      unit: "of",
      ...common,
    });
    put("security_cases", {
      label: "Security cases passed (T1 to T5 and E1 to E5)",
      value: cases.passed,
      of: cases.total,
      unit: "of",
      ...common,
    });
  }

  // The same tests on the deployed app.
  const LIVE_RUN = "evals/runs/security-live-full-stack.json";
  const live = read(LIVE_RUN);
  if (live)
    put("live_app", {
      label: "Security cases passed on the deployed app",
      value: live.results.filter((r) => r.pass).length,
      of: live.results.length,
      unit: "of",
      split: `evals/security.mjs against ${live.base}, each case worst of ${live.runs}, one run at a time, graded on the audit log`,
      system: `the deployed app with its defaults (classifier on): ${COMPLETE_SYSTEM}, intake, the agent with all tools`,
      run: LIVE_RUN,
      at: live.at,
    });

  // Legal lookup: deterministic, measured by evals/history.mjs each time it runs.
  const legal = history.rows.filter((r) => r.track === "legal" && r.kept);
  if (legal.length) {
    const common = {
      system: "the lookup tool as shipped (src/primitives/lookup-ranking.ts)",
      run: "evals/climb-history.json (node evals/legal.mjs, no network)",
      at: history.generated,
    };
    put("legal_recall_tuning", {
      label: "Legal lookup recall@3, tuning questions",
      value: legal.at(-1).scores.retrieval_recall_at_3,
      start: legal[0].scores.retrieval_recall_at_3,
      unit: "0-1",
      split: "evals/legal/dev.jsonl (54 questions)",
      ...common,
    });
    if (history.legal_heldout)
      put("legal_recall_unseen", {
        label: "Legal lookup recall@3, unseen questions",
        value: history.legal_heldout.end.retrieval_recall_at_3,
        start: history.legal_heldout.start.retrieval_recall_at_3,
        unit: "0-1",
        split: history.legal_heldout.split,
        ...common,
      });
  }

  // The agent end to end, with the lookup tool and without it.
  for (const [key, name, label] of [
    ["lookup_with", "agent-a0-default", "End-to-end claims passed, agent with the lookup tool"],
    [
      "lookup_without",
      "agent-a9-tools-no-lookup",
      "End-to-end claims passed, agent without the lookup tool",
    ],
  ]) {
    const file = `evals/runs/${name}.json`;
    const r = read(file);
    if (!r) continue;
    // A run records the switches each session really had; before 21 Nov 05:30 CET the classifier default was off.
    const classifier = r.results.find((x) => x.switches)?.switches?.classifier ?? "off";
    put(key, {
      label,
      value: r.scores.agent_pass,
      unit: "%",
      split: `evals/agent/dev.jsonl (${r.results.length} claims, one run each, a scripted reviewer answers every handoff)`,
      system: `the agent on ${r.base}, classifier ${classifier}${classifier === "on" ? "" : " (the default when this ran; not re-measured with the classifier on)"}`,
      run: file,
      at: r.at,
    });
  }

  // Our routing against asking a model whether a claim is sensitive.
  const COMPARE_RUN = "evals/compare-latest.json";
  const compare = read(COMPARE_RUN);
  if (compare?.at)
    for (const [build, name, system] of [
      ["harness", "the complete system", COMPLETE_SYSTEM],
      [
        "brane",
        "BRANE with our policy alone",
        "BRANE claims-v6.1 alone, no pre-mask, no classifier",
      ],
      [
        "ask-llm",
        "a model asked whether each claim is sensitive",
        "BRANE's local model asked for a label per claim",
      ],
    ]) {
      const s = compare.summary[build];
      const id = build.replace("-", "_");
      const common = {
        split: `${s.claims} of our 30 claims that every build judged, ${compare.runs} runs each, one request at a time`,
        system,
        run: COMPARE_RUN,
        at: compare.at,
      };
      put(`compare_${id}_unsafe`, {
        label: `Unsafe decisions, ${name}`,
        value: s.unsafe,
        of: s.decisions,
        unit: "of",
        ...common,
      });
      put(`compare_${id}_correct`, {
        label: `Correct decisions, ${name}`,
        value: s.correct,
        of: s.decisions,
        unit: "of",
        ...common,
      });
      put(`compare_${id}_stable`, {
        label: `Claims decided the same on every run, ${name}`,
        value: s.stable,
        of: s.claims,
        unit: "of",
        ...common,
      });
    }

  return {
    about:
      "The single source for every number the README, submission/README.md, docs/evals.md, docs/track.md and the video quote. Read values.<key>.value (with .of for counts and .start for the baseline before any change). scripts/numbers-check.mjs fails when a document states something else.",
    system: COMPLETE_SYSTEM,
    values,
  };
}

export const showValue = (e, v = e.value) =>
  v === null || v === undefined
    ? "n/a"
    : e.unit === "%"
      ? `${v}%`
      : e.unit === "of"
        ? `${v} of ${e.of}`
        : String(v);

/** The table every document carries between the headline markers. */
export function renderHeadline(headline) {
  const rows = Object.values(headline.values).map(
    (e) =>
      `| ${e.label} | ${showValue(e)} | ${e.start === undefined ? "" : showValue(e, e.start)} | ${e.split ?? ""} | ${e.system} | \`${e.run}\` | ${cet(e.at)} |`,
  );
  return [
    "| Number | Result | Before any change | Measured on | System | Run file | Run time |",
    "| ------ | ------ | ----------------- | ----------- | ------ | -------- | -------- |",
    ...rows,
  ].join("\n");
}
